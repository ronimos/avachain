def _validate(cfg: dict) -> list[str]:
    warnings = []
    sp = cfg.get("snowpack", {})
    if sp.get("binary") and not Path(sp["binary"]).exists():
        warnings.append(f"SNOWPACK binary not found: {sp['binary']}")
    if sp.get("season_end", "YYYY-MM-DD") == "YYYY-MM-DD":
        warnings.append("snowpack.season_end is not set — edit the TOML before running SNOWPACK")
    stations = {s["role"]: s for s in cfg.get("stations", [])}
    for role in ("summit", "base"):
        if role not in stations:
            warnings.append(f"No [[stations]] entry with role = \"{role}\"")
        elif not stations[role].get("sql_id"):
            warnings.append(f"stations[{role}].sql_id is empty")
    if cfg["paths"].get("project_dir") in ("/path/to/snowpack_model_feeder", "/path/to/avachain", ""):
        warnings.append("paths.project_dir still has the template placeholder value")
    output_dir = cfg["paths"].get("output_dir", "")
    if output_dir in ("outputs", ""):
        slope_name = cfg["slope"]["name"]
        warnings.append(
            f"paths.output_dir = 'outputs' — use 'outputs/{slope_name}' "
            f"so each slope's outputs stay separate"
        )
    return warnings


