    lines.append("    --date-before 2026-01-14 --date-after 2026-01-20")
    lines.append("```")

    lines.append("\n### Skip NWP forecast extension")
    lines.append("```bash")
    lines.append(f"./{operational_script.name} --no-nwp")
    lines.append("```")

    lines.append("\n### Re-run SNOWPACK only (all clusters)")
    lines.append("```bash")
    lines.append(f"bash slopes/{name}/run_snowpack.sh")
    lines.append("```")

    lines.append("\n### Re-run install (e.g., after config change)")
    lines.append("```bash")
    lines.append(f"python install.py --slope {name}")
    lines.append("# Add --skip-wrf if /ssd is not mounted")
    lines.append("# Add --force to regenerate master_config.ini and template.sno")
    lines.append("```")

    return "\n".join(lines) + "\n"


