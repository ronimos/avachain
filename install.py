    for p in (ini_path, template_sno, snowpack_script, operational_script):
        lines.append(f"- `{p}`")

    # --- Common operations ---
    h2("Common Operations")

    lines.append("\n### Normal daily update (after new UAS survey)")
    lines.append("```bash")
    lines.append(f"./{operational_script.name} --survey data/surveys/YYYYMMDD.tif")
    lines.append("```")

    lines.append("\n### Snapshot at a specific date (no new survey)")
