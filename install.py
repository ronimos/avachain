def _render_admin_doc(
    cfg: dict,
    project_dir: Path,
    toml_path: Path,
    ini_path: Path,
    template_sno: Path,
    snowpack_script: Path,
    operational_script: Path,
    wrf: dict | None,
    warnings: list[str],
) -> str:
    slope    = cfg["slope"]
    paths    = cfg["paths"]
    sp       = cfg.get("snowpack", {})
    sc       = cfg.get("scenarios", {})
    wrf_cfg  = cfg.get("wrf", {})
    cron_cfg = cfg.get("cron", {})

    name         = slope["name"]
    display_name = slope.get("display_name", name)
    hour_utc     = cron_cfg.get("hour_utc", 20)
    log_path     = project_dir / "outputs" / "logs" / f"cron_{name}.log"

    lines: list[str] = []

    def h1(t: str) -> None: lines.append(f"# {t}")
    def h2(t: str) -> None: lines.append(f"\n## {t}")
    def kv(k: str, v: object) -> None: lines.append(f"- **{k}**: {v}")

    h1(f"Admin Reference — {display_name}")
    lines.append(f"\nGenerated by `install.py` from `{toml_path.relative_to(project_dir)}`")
    lines.append(f"\n> Keep this file alongside `slope_config.toml`. "
                 "Re-run `install.py` to regenerate after any config change.\n")

    # --- Warnings ---
    if warnings:
        h2("Configuration Warnings")
        for w in warnings:
            lines.append(f"- ⚠  {w}")

    # --- Slope identity ---
    h2("Slope Identity")
    kv("Name", name)
    kv("Display name", display_name)
    kv("Aspect", f"{slope.get('aspect_deg', '?')}°")
    kv("Slope angle", f"{slope.get('slope_angle_deg', '?')}°")
    kv("Elevation", f"{slope.get('elevation_m', '?')} m")
    kv("Lat / Lon", f"{slope.get('latitude', '?')}, {slope.get('longitude', '?')}")
    if notes := slope.get("notes"):
        kv("Notes", notes)

    # --- Key paths ---
    h2("Key Paths")
    kv("Project root", f"`{project_dir}`")
    kv("Config (TOML)", f"`{toml_path}`")
    kv("DEM", f"`{project_dir / paths.get('dem', '—')}`")
    kv("Survey dir", f"`{project_dir / paths.get('survey_dir', '—')}`")
    kv("Weather CSV", f"`{project_dir / paths.get('weather_csv', '—')}`")
    kv("Boundary KML", f"`{project_dir / paths.get('boundary_kml', '—')}`")
    kv("Start-zone KML", f"`{project_dir / paths.get('start_zone_kml', '—')}`")
    kv("Release GeoJSON", f"`{project_dir / paths.get('release_geojson', '—')}`")
    kv("Output dir", f"`{project_dir / paths.get('output_dir', 'outputs')}`")
    kv("SNOWPACK slope dir", f"`{project_dir / paths.get('slope_dir', f'snowpack/{name}')}`")

    # --- SNOWPACK ---
    h2("SNOWPACK Configuration")
    kv("Binary", f"`{sp.get('binary', '—')}`")
    kv("Lib dir", f"`{sp.get('lib_dir', '—')}`")
    kv("Season start", sp.get("season_start", "not set"))
    kv("Season end", sp.get("season_end", "not set"))
    kv("Max parallel jobs", sp.get("max_parallel_jobs", 30))

    # --- Weather stations ---
    h2("Weather Stations")
    for stn in cfg.get("stations", []):
        role = stn.get("role", "?")
        lines.append(f"\n**{role.capitalize()}** — `{stn.get('sql_id', '?')}` "
                     f"({stn.get('name', '?')})")
        kv("Elevation", f"{stn.get('elev_m', '?')} m")
        kv("Lat / Lon", f"{stn.get('lat', '?')}, {stn.get('lon', '?')}")
        cols = stn.get("sql_columns", [])
        if cols:
            kv("Columns ingested", ", ".join(f"`{c}`" for c in cols))

    # --- WRF / NWP ---
    h2("WRF / NWP Grid Cell")
    if wrf:
        kv("Zone", wrf["zone"])
