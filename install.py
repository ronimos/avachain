def _find_season_dir(fcst_base: Path) -> Path | None:
    """Return the most recent year-only directory (e.g. '2025', not '2025-01-31')."""
    dirs = [d for d in fcst_base.iterdir()
            if d.is_dir() and re.fullmatch(r'\d{4}', d.name)]
    return max(dirs, key=lambda d: d.name) if dirs else None


def _read_smet_latlon(path: Path) -> tuple[float, float] | None:
    """Read latitude and longitude from a SMET file header. Returns None on error."""
    lat = lon = None
    try:
        with open(path) as f:
            for line in f:
                stripped = line.strip()
                if stripped == "[DATA]":
                    break
                if "=" in stripped and not stripped.startswith("["):
                    k, _, v = stripped.partition("=")
                    k = k.strip()
                    if k == "latitude":
                        lat = float(v.strip())
                    elif k == "longitude":
                        lon = float(v.strip())
                if lat is not None and lon is not None:
                    return lat, lon
    except Exception:
        return None
    return (lat, lon) if lat is not None and lon is not None else None


def _read_smet_slope_azi(path: Path) -> float | None:
    """Read slope_azi from a SMET file header."""
    try:
        with open(path) as f:
            for line in f:
                stripped = line.strip()
                if stripped == "[DATA]":
                    break
                if stripped.startswith("slope_azi"):
                    _, _, v = stripped.partition("=")
                    return float(v.strip())
    except Exception:
        return None
    return None


def _haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    R = 6371.0
    dlat = math.radians(lat2 - lat1)
    dlon = math.radians(lon2 - lon1)
    a = (math.sin(dlat / 2) ** 2
         + math.cos(math.radians(lat1)) * math.cos(math.radians(lat2))
         * math.sin(dlon / 2) ** 2)
    return 2 * R * math.asin(math.sqrt(a))


def _aspect_diff(a1: float, a2: float) -> float:
    d = abs(a1 - a2) % 360
    return min(d, 360 - d)


def _find_best_wrf(cfg: dict) -> dict | None:
    """
    Scan WRF forecast directories and return the closest grid cell with the
    best aspect match to the slope.

    Each grid-cell directory contains:
      <grid_id>_res.smet          — flat field (slope_angle=0)
      <grid_id>1_res.smet …       — aspect variants (slope_azi 0/90/180/270)

    Returns a dict with: zone, grid_id, smet_dir, smet_file, lat, lon,
    slope_azi, dist_km.  Returns None if the fcst directory is unavailable.
    """
    wrf_cfg = cfg.get("wrf", {})
    fcst_base_str = wrf_cfg.get("fcst_base_dir", "")
    if not fcst_base_str:
        return None
    fcst_base = Path(fcst_base_str)
    if not fcst_base.exists():
        return None

    season_name = wrf_cfg.get("season", "")
    if season_name:
        season_dir = fcst_base / season_name
    else:
        season_dir = _find_season_dir(fcst_base)

    if not season_dir or not season_dir.exists():
        return None

    slope_lat  = float(cfg["slope"].get("latitude", 0))
    slope_lon  = float(cfg["slope"].get("longitude", 0))
    slope_asp  = float(cfg["slope"].get("aspect_deg", 0))

    print(f"  Scanning WRF zones in {season_dir} ...")

    best_dist    = float("inf")
    best_cell: dict | None = None

    for zone_dir in sorted(season_dir.glob("zone*")):
        for grid_dir in sorted(zone_dir.iterdir()):
            if not grid_dir.is_dir():
                continue
            flat_smet = grid_dir / f"{grid_dir.name}_res.smet"
            if not flat_smet.exists():
                smets = sorted(grid_dir.glob("*_res.smet"))
                if not smets:
                    continue
                flat_smet = smets[0]

            coords = _read_smet_latlon(flat_smet)
            if coords is None:
                continue
            lat, lon = coords
            dist = _haversine_km(slope_lat, slope_lon, lat, lon)
            if dist < best_dist:
                best_dist = dist
                best_cell = {
                    "zone": zone_dir.name,
                    "grid_id": grid_dir.name,
                    "grid_dir": grid_dir,
                    "lat": lat,
                    "lon": lon,
                    "dist_km": dist,
                }

    if best_cell is None:
        return None

    # Among aspect variants in the selected cell, pick the closest aspect match
    grid_dir = best_cell["grid_dir"]
    flat_name = f"{grid_dir.name}_res.smet"
    aspect_smets = sorted(f for f in grid_dir.glob("*_res.smet")
                          if f.name != flat_name)

    selected_smet = grid_dir / flat_name   # fallback to flat
    selected_azi  = 0.0

    if aspect_smets:
        best_diff = float("inf")
        for smet in aspect_smets:
            azi = _read_smet_slope_azi(smet)
            if azi is None:
                continue
            diff = _aspect_diff(slope_asp, azi)
            if diff < best_diff:
                best_diff    = diff
                selected_smet = smet
                selected_azi  = azi

    return {
        "zone":      best_cell["zone"],
        "grid_id":   best_cell["grid_id"],
        "smet_dir":  str(grid_dir),
        "smet_file": str(selected_smet),
        "lat":       best_cell["lat"],
        "lon":       best_cell["lon"],
        "dist_km":   best_cell["dist_km"],
        "slope_azi": selected_azi,
    }


def _update_wrf_in_toml(toml_path: Path, wrf: dict) -> None:
    """Write WRF selection results back into the [wrf] section of the TOML."""
    text = toml_path.read_text()
    # String fields — always written with quotes
    str_fields = {
        "wrf_smet_dir":  wrf["smet_dir"],
        "wrf_zone":      wrf["zone"],
        "wrf_grid_id":   wrf["grid_id"],
        "wrf_smet_file": wrf["smet_file"],
    }
    for key, value in str_fields.items():
        text = re.sub(
            rf'^({re.escape(key)}\s*=\s*)""',
            rf'\g<1>"{value}"',
            text,
            flags=re.MULTILINE,
        )
    # Float field — written without quotes
    dist_str = str(round(wrf["dist_km"], 3))
    text = re.sub(
        r'^(wrf_dist_km\s*=\s*)0\.0',
        rf'\g<1>{dist_str}',
        text,
        flags=re.MULTILINE,
    )
    toml_path.write_text(text)


