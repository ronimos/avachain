def main() -> None:
    parser = argparse.ArgumentParser(
        description="Bootstrap a new slope for the avachain pipeline.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python install.py slopes/little_prof/slope_config.toml
  python install.py --slope little_prof
  python install.py --list
""",
    )
    parser.add_argument("toml", nargs="?", help="Path to slope_config.toml")
    parser.add_argument("--slope", metavar="NAME",
                        help="Slope name; resolves to slopes/<name>/slope_config.toml")
    parser.add_argument("--list", action="store_true",
                        help="List all configured slopes and exit")
    parser.add_argument("--skip-wrf", action="store_true",
                        help="Skip WRF zone discovery (useful when /ssd is not mounted)")
    args = parser.parse_args()

    repo_root = Path(__file__).parent

    if args.list:
        _list_slopes(repo_root)
        return

    if args.toml:
        toml_path = Path(args.toml)
    elif args.slope:
        toml_path = _find_toml(repo_root, args.slope)
    else:
        parser.error("Provide a TOML path or --slope <name>")

    if not toml_path.exists():
        sys.exit(f"ERROR: config not found: {toml_path}")

    cfg          = _load_toml(toml_path)
    slope_name   = cfg["slope"]["name"]
    display_name = cfg["slope"].get("display_name", slope_name)
    project_dir  = Path(cfg["paths"]["project_dir"])

    print(f"\n=== Installing slope: {display_name} ({slope_name}) ===\n")

    warnings = _validate(cfg)
    if warnings:
        print("  Warnings:")
        for w in warnings:
            print(f"    ⚠  {w}")
        print()

    # --- Directories ---
    print("Creating directory structure...")
    _make_dirs(cfg)
    print()

    # --- WRF zone discovery ---
    if not args.skip_wrf:
        print("Finding closest WRF grid cell...")
        wrf = _find_best_wrf(cfg)
        if wrf:
            print(f"  Selected: {wrf['zone']}/{wrf['grid_id']}")
            print(f"  Distance: {wrf['dist_km']:.1f} km")
            print(f"  Aspect variant: slope_azi={wrf['slope_azi']:.0f}°  "
                  f"(slope aspect={cfg['slope'].get('aspect_deg', '?')}°)")
            print(f"  File: {wrf['smet_file']}")
            _update_wrf_in_toml(toml_path, wrf)
            print(f"  → Written to {toml_path.name}")
        else:
            print("  WRF directory not accessible — skipping. "
                  "Rerun without --skip-wrf when /ssd is mounted.")
        print()
    else:
        print("Skipping WRF discovery (--skip-wrf).\n")

    # --- master_config.ini ---
    ini_path = project_dir / "slopes" / slope_name / "config" / "master_config.ini"
    # Don't overwrite an existing customised ini
    if ini_path.exists():
        print(f"Skipping master_config.ini (already exists at {ini_path})")
    else:
        ini_path.write_text(_render_master_ini(cfg))
        print(f"Wrote {ini_path.relative_to(project_dir)}")
    print()

    # --- run_snowpack.sh ---
    snowpack_script = project_dir / "slopes" / slope_name / "run_snowpack.sh"
    print(f"Writing {snowpack_script.relative_to(project_dir)} ...")
    _write_script(snowpack_script, _render_run_snowpack(cfg))

    # --- run_<slope>.sh ---
    operational_script = project_dir / f"run_{slope_name}.sh"
    print(f"Writing {operational_script.name} ...")
    _write_script(operational_script, _render_run_operational(cfg))

    # --- Cron ---
    hour_utc  = cfg.get("cron", {}).get("hour_utc", 20)
    log_path  = project_dir / "outputs" / "logs" / f"cron_{slope_name}.log"

    print()
    print("=" * 60)
    print("Installation complete.")
    print()
    print("Next steps:")
    print(f"  1. Drop DEM          → {cfg['paths'].get('dem', f'data/{slope_name}/dem/')}")
    print(f"  2. Drop first survey → {cfg['paths'].get('survey_dir', f'data/{slope_name}/surveys/')}/")
    print(f"  3. Drop template.sno → "
          f"{cfg['paths'].get('slope_dir', f'snowpack/{slope_name}')}/input/snow/")
    print()
    # If this looks like an existing installation being re-run with a newly
    # namespaced output_dir, print the one-time migration commands.
    out_dir = cfg["paths"].get("output_dir", "")
    if out_dir and out_dir != "outputs":
        flat_out = project_dir / "outputs"
        if (flat_out / "analysis").exists() and not (project_dir / out_dir / "analysis").exists():
            print("  *** One-time migration needed — move existing outputs into the")
            print(f"  *** new per-slope directory ({out_dir}):")
            print()
            print(f"    mkdir -p {project_dir}/{out_dir}")
            print(f"    for d in analysis scenarios plots models hourly_grids resampled_1m logs; do")
            print(f"      [ -d {flat_out}/$d ] && mv {flat_out}/$d {project_dir}/{out_dir}/$d")
            print(f"    done")
            print(f"    # outputs/weather stays in place (shared across slopes)")
            print()
    print()
    print("To schedule the daily run, add this line to your crontab")
    print("(run: crontab -e):")
    print()
    print(f"  0 {hour_utc} * * * {operational_script} >> {log_path} 2>&1")
    print()
    print("Generated files:")
    print(f"  {ini_path}")
    print(f"  {snowpack_script}")
    print(f"  {operational_script}")
    print("=" * 60)


if __name__ == "__main__":
    main()
