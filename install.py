def _make_dirs(cfg: dict) -> None:
    project_dir = Path(cfg["paths"]["project_dir"])
    slope_name  = cfg["slope"]["name"]
    paths       = cfg["paths"]
    slope_dir   = project_dir / paths.get("slope_dir",   f"snowpack/{slope_name}")
    output_dir  = project_dir / paths.get("output_dir",  f"outputs/{slope_name}")

    # Input dirs — derived from TOML paths so each slope is self-contained
    file_keys = ("dem", "weather_csv", "boundary_kml", "start_zone_kml", "release_geojson")
    dir_keys  = ("survey_dir",)
    dirs: list[Path] = []
    for k in file_keys:
        if v := paths.get(k):
            dirs.append((project_dir / v).parent)
    for k in dir_keys:
        if v := paths.get(k):
            dirs.append(project_dir / v)

    # Slope runtime dirs
    dirs += [
        slope_dir / "input" / "snow",
        slope_dir / "input" / "smet",
        slope_dir / "output",
    ]

    # Per-slope output dirs
    for sub in ("analysis", "scenarios", "plots", "models", "hourly_grids",
                "resampled_1m", "logs"):
        dirs.append(output_dir / sub)

    # Shared dirs (not namespaced — used by all slopes)
    dirs += [
        project_dir / "outputs" / "weather",
        project_dir / "slopes" / slope_name / "config",
        project_dir / "slopes" / slope_name / "external_models",
    ]

    # Deduplicate while preserving order
    seen: set[Path] = set()
    unique: list[Path] = []
    for d in dirs:
        if d not in seen:
            seen.add(d)
            unique.append(d)

    created = [d for d in unique if not d.exists()]
    for d in created:
        d.mkdir(parents=True, exist_ok=True)
    if created:
        print(f"  Created {len(created)} director(ies):")
        for d in created:
            print(f"    {d.relative_to(project_dir)}")
    else:
        print("  All directories already exist.")


