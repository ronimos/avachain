def _load_toml(path: Path) -> dict:
    with open(path, "rb") as f:
        return tomllib.load(f)


def _find_toml(repo_root: Path, slope_name: str) -> Path:
    return repo_root / "slopes" / slope_name / "slope_config.toml"


def _list_slopes(repo_root: Path) -> None:
    tomls = sorted((repo_root / "slopes").glob("*/slope_config.toml"))
    if not tomls:
        print("No slope_config.toml files found under slopes/")
        return
    print(f"{'Slope name':<20}  {'Display name':<30}  Config")
    print("-" * 80)
    for p in tomls:
        try:
            data = _load_toml(p)
            name    = data.get("slope", {}).get("name", "?")
            display = data.get("slope", {}).get("display_name", "?")
            print(f"{name:<20}  {display:<30}  {p}")
        except Exception as e:
            print(f"{'(error)':<20}  {str(e):<30}  {p}")


